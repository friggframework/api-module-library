#!/usr/bin/env node
/**
 * Generate MODULES.md — index of API modules under modules/ and archive/.
 *
 * Usage:
 *   node scripts/gen-modules-index.js          # write MODULES.md
 *   node scripts/gen-modules-index.js --check  # exit 1 if MODULES.md is stale
 *   node scripts/gen-modules-index.js --stdout # print markdown only
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'MODULES.md');

/**
 * Status preserved from the pre-flatten layout (packages/needs-updating vs
 * packages/v1-ready). New modules under modules/ default to v1-ready.
 * qbo lives in archive/ and is always "archived".
 */
const NEEDS_UPDATING = new Set([
  'activecampaign',
  'airwallex',
  'attentive',
  'clyde',
  'fastspring-iq',
  'freshbooks',
  'front',
  'gorgias',
  'huggg',
  'marketo',
  'microsoft-teams',
  'monday',
  'netx',
  'outreach',
  'personio',
  'revio',
  'rollworks',
  'salesloft',
  'sharepoint',
  'slack',
  'terminus',
  'yotpo',
]);

const AUTH_TYPES = new Set([
  'oauth2',
  'apiKey',
  'basic',
  'clientCredentials',
  'token',
]);

function readSafe(filePath) {
  try {
    return fs.readFileSync(filePath, 'utf8');
  } catch {
    return '';
  }
}

function collectSourceText(moduleDir) {
  const chunks = [];
  const preferred = [
    'definition.js',
    'definition.ts',
    'defaultConfig.json',
    'api.js',
    'api.ts',
    'index.js',
    'index.ts',
    'authFields.js',
    path.join('src', 'defintion.ts'),
    path.join('src', 'definition.ts'),
    path.join('src', 'api.ts'),
    path.join('src', 'index.ts'),
  ];
  for (const rel of preferred) {
    const full = path.join(moduleDir, rel);
    if (fs.existsSync(full) && fs.statSync(full).isFile()) {
      chunks.push(readSafe(full));
    }
  }
  return chunks.join('\n');
}

function detectAuthType(moduleDir, text) {
  // Prefer explicit auth requirement literals (avoid nested jsonSchema "type": "object").
  const authBlock = text.match(
    /getAuthorizationRequirements[\s\S]{0,800}?type:\s*['"]([^'"]+)['"]/
  );
  if (authBlock && AUTH_TYPES.has(authBlock[1])) {
    return authBlock[1];
  }

  const reqType = text.match(
    /getAuthorizationRequirements[\s\S]{0,400}?type:\s*Api\.requesterType/
  );
  if (reqType) {
    const apiText =
      readSafe(path.join(moduleDir, 'api.js')) ||
      readSafe(path.join(moduleDir, 'api.ts')) ||
      readSafe(path.join(moduleDir, 'src', 'api.ts'));
    if (/OAuth2Requester/.test(apiText)) return 'oauth2';
    if (/ApiKeyRequester/.test(apiText)) return 'apiKey';
    if (/BasicAuthRequester|BasicRequester/.test(apiText)) return 'basic';
  }

  if (/extends\s+OAuth2Requester|OAuth2Requester/.test(text)) return 'oauth2';
  if (/extends\s+ApiKeyRequester|ApiKeyRequester/.test(text)) return 'apiKey';
  if (/BasicAuthRequester|authFields/.test(text)) return 'basic';
  if (/getTokenFromCode/.test(text)) return 'oauth2';
  if (/setApiKey|api_key|API_KEY/.test(text)) return 'apiKey';

  return 'unknown';
}

function moduleStatus(name, location) {
  if (location === 'archive') return 'archived';
  if (NEEDS_UPDATING.has(name)) return 'needs-updating';
  return 'v1-ready';
}

function listModuleDirs(parent, location) {
  const abs = path.join(ROOT, parent);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith('.'))
    .map((d) => ({
      name: d.name,
      location,
      dir: path.join(abs, d.name),
    }));
}

function loadPackage(moduleDir) {
  const pkgPath = path.join(moduleDir, 'package.json');
  if (!fs.existsSync(pkgPath)) {
    return { packageName: '—', version: '—' };
  }
  try {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    return {
      packageName: pkg.name || '—',
      version: pkg.version || '—',
    };
  } catch {
    return { packageName: '—', version: '—' };
  }
}

function gatherRows() {
  const entries = [
    ...listModuleDirs('modules', 'modules'),
    ...listModuleDirs('archive', 'archive'),
  ].sort((a, b) => a.name.localeCompare(b.name));

  return entries.map((entry) => {
    const text = collectSourceText(entry.dir);
    const { packageName, version } = loadPackage(entry.dir);
    return {
      module: entry.name,
      packageName,
      version,
      authType: detectAuthType(entry.dir, text),
      status: moduleStatus(entry.name, entry.location),
      path: path.relative(ROOT, entry.dir),
    };
  });
}

function renderMarkdown(rows) {
  const lines = [
    '<!-- Generated by scripts/gen-modules-index.js. Do not edit by hand. -->',
    '<!-- Run: npm run modules:index -->',
    '',
    '# Modules',
    '',
    'Flat index of API modules. Publishable packages live under `modules/*`',
    '(see `lerna.json`). `archive/*` and `tools/*` are not published.',
    '',
    '| Module | Package name | Version | Auth type | Status |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const row of rows) {
    lines.push(
      `| [\`${row.module}\`](${row.path}/) | \`${row.packageName}\` | ${row.version} | ${row.authType} | ${row.status} |`
    );
  }

  lines.push('');
  return `${lines.join('\n')}\n`;
}

function main() {
  const args = new Set(process.argv.slice(2));
  const rows = gatherRows();
  const markdown = renderMarkdown(rows);

  if (args.has('--stdout')) {
    process.stdout.write(markdown);
    return;
  }

  if (args.has('--check')) {
    const existing = fs.existsSync(OUT_FILE)
      ? fs.readFileSync(OUT_FILE, 'utf8')
      : '';
    if (existing !== markdown) {
      console.error(
        'MODULES.md is stale. Run `npm run modules:index` and commit the result.'
      );
      process.exit(1);
    }
    console.log('MODULES.md is up to date.');
    return;
  }

  fs.writeFileSync(OUT_FILE, markdown);
  console.log(
    `Wrote ${path.relative(ROOT, OUT_FILE)} (${rows.length} modules).`
  );
}

main();
